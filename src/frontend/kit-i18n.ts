// Strings for the UI Kit screens (dashboard gadget, settings), picked from the Jira user's locale.
export type KitLang = 'en' | 'fr' | 'ar';

export function langFromLocale(locale?: string): KitLang {
  const l = (locale ?? 'en').slice(0, 2).toLowerCase();
  return l === 'fr' || l === 'ar' ? l : 'en';
}

